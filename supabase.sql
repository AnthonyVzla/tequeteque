create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  first_name text not null default '',
  last_name text not null default '',
  national_id text unique,
  phone text,
  avatar_url text,
  points bigint not null default 0 check(points >= 0),
  period_points bigint not null default 0 check(period_points >= 0),
  referral_code text unique,
  referral_owner_id uuid references public.profiles(id),
  role text not null default 'player' check(role in ('player','admin')),
  suspended boolean not null default false,
  ip_hashes jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.points_ledger (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  amount bigint not null,
  type text not null,
  note text,
  created_at timestamptz not null default now()
);

create table if not exists public.purchase_codes (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references public.profiles(id) on delete cascade,
  code text unique not null check(code ~ '^[0-9]{6}$'),
  used boolean not null default false,
  used_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.prizes (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  points bigint not null check(points > 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.redemptions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id),
  prize_id uuid not null references public.prizes(id),
  purchase_code_id uuid not null references public.purchase_codes(id),
  points bigint not null,
  created_at timestamptz not null default now()
);

create table if not exists public.account_ip_alerts (
  id bigint generated by default as identity primary key,
  ip_hash text not null unique,
  account_count integer not null,
  resolved boolean not null default false,
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  insert into public.profiles(id,first_name,last_name,national_id,phone,referral_code)
  values(new.id,coalesce(new.raw_user_meta_data->>'first_name',''),coalesce(new.raw_user_meta_data->>'last_name',''),
         new.raw_user_meta_data->>'national_id',new.raw_user_meta_data->>'phone',
         upper(substr(replace(gen_random_uuid()::text,'-',''),1,8)));
  return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

create or replace function public.award_game_points(p_points bigint)
returns void language plpgsql security definer set search_path=public as $$
begin
  if p_points < 0 or p_points > 50000 then raise exception 'Invalid score'; end if;
  update public.profiles set points=points+p_points, period_points=period_points+p_points where id=auth.uid() and not suspended;
  insert into public.points_ledger(user_id,type,amount,note)
  values(auth.uid(),'game',greatest(p_points,0),'Puntos obtenidos jugando');
end $$;

create or replace function public.redeem_prize(p_prize_id uuid,p_code text)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_cost bigint; v_code_id uuid; v_points bigint;
begin
  select points into v_cost from public.prizes where id=p_prize_id and active=true for update;
  if v_cost is null then return jsonb_build_object('success',false,'message','El premio no está disponible'); end if;
  select points into v_points from public.profiles where id=auth.uid() for update;
  if v_points < v_cost then return jsonb_build_object('success',false,'message','Puntos insuficientes'); end if;
  select id into v_code_id from public.purchase_codes where code=p_code and user_id=auth.uid() and used=false for update;
  if v_code_id is null then return jsonb_build_object('success',false,'message','Código inválido, no asignado o ya utilizado'); end if;
  update public.profiles set points=points-v_cost where id=auth.uid();
  update public.purchase_codes set used=true,used_at=now() where id=v_code_id;
  insert into public.redemptions(user_id,prize_id,purchase_code_id,points) values(auth.uid(),p_prize_id,v_code_id,v_cost);
  insert into public.points_ledger(user_id,type,amount,note) values(auth.uid(),'redemption',-v_cost,'Redención de premio');
  return jsonb_build_object('success',true);
end $$;

create or replace function public.apply_referral(p_new_user uuid,p_code text)
returns void language plpgsql security definer set search_path=public as $$
declare v_owner uuid;
begin
  if auth.uid() is distinct from p_new_user then raise exception 'No autorizado'; end if;
  select id into v_owner from public.profiles where referral_code=p_code;
  if v_owner is null or v_owner=p_new_user then return; end if;
  update public.profiles set referral_owner_id=v_owner where id=p_new_user and referral_owner_id is null;
  update public.profiles set points=points+100,period_points=period_points+100 where id in (p_new_user,v_owner);
  insert into public.points_ledger(user_id,type,amount,note) values
    (p_new_user,'referral',100,'Bono por registro referido'),
    (v_owner,'referral',100,'Bono por referido nuevo');
end $$;

alter table public.profiles enable row level security;
alter table public.points_ledger enable row level security;
alter table public.purchase_codes enable row level security;
alter table public.prizes enable row level security;
alter table public.redemptions enable row level security;
alter table public.account_ip_alerts enable row level security;

create policy "Read own profile" on public.profiles for select using(auth.uid()=id or exists(select 1 from public.profiles a where a.id=auth.uid() and a.role='admin'));
create policy "Update own profile" on public.profiles for update using(auth.uid()=id) with check(auth.uid()=id and role=(select role from public.profiles where id=auth.uid()));
create policy "Admin profiles" on public.profiles for update using(exists(select 1 from public.profiles a where a.id=auth.uid() and a.role='admin'));
create policy "Own ledger" on public.points_ledger for select using(auth.uid()=user_id or exists(select 1 from public.profiles a where a.id=auth.uid() and a.role='admin'));
create policy "Public active prizes" on public.prizes for select using(active=true or exists(select 1 from public.profiles where id=auth.uid() and role='admin'));
create policy "Admin prizes" on public.prizes for all using(exists(select 1 from public.profiles where id=auth.uid() and role='admin'));
create policy "Own purchase codes" on public.purchase_codes for select using(auth.uid()=user_id or exists(select 1 from public.profiles where id=auth.uid() and role='admin'));
create policy "Admin purchase codes" on public.purchase_codes for all using(exists(select 1 from public.profiles where id=auth.uid() and role='admin'));
create policy "Admin IP alerts" on public.account_ip_alerts for all using(exists(select 1 from public.profiles where id=auth.uid() and role='admin'));

grant usage on schema public to anon, authenticated;
grant select on public.profiles,public.prizes to anon, authenticated;
grant select,insert,update,delete on public.purchase_codes,public.prizes to authenticated;
grant select,update on public.profiles to authenticated;
grant execute on function public.award_game_points(bigint),public.redeem_prize(uuid,text) to authenticated;
grant execute on function public.apply_referral(uuid,text) to authenticated;

